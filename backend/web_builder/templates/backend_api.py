    "id INTEGER PRIMARY KEY AUTOINCREMENT, kind TEXT NOT NULL, payload TEXT NOT NULL, "
    "status TEXT NOT NULL DEFAULT 'queued', run_at REAL NOT NULL, "
    "attempts INTEGER NOT NULL DEFAULT 0, max_attempts INTEGER NOT NULL, "
