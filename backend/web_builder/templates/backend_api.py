def _sqlite_ddl(table: str, fields: List[dict]) -> str:
    cols = ["id INTEGER PRIMARY KEY AUTOINCREMENT"]
    for f in fields:
        col = "%s %s" % (f["name"], SQLITE_TYPE[f["type"]])
        if f["required"]:
            col += " NOT NULL"
        if f["unique"]:
            col += " UNIQUE"
        cols.append(col)
    cols.append("created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP")
    return "CREATE TABLE IF NOT EXISTS %s (%s);" % (table, ", ".join(cols))


def _pydantic_lines(fields: List[dict], indent: str = "    ") -> List[str]:
    lines: List[str] = []
    for f in fields:
        name, t = f["name"], PY_TYPE[f["type"]]
        optional = not f["required"]
        opt = " = None" if optional else ""
        if f["type"] in ("str", "email", "text"):
            if optional:
                lines.append("%s%s: Optional[str] = Field(default=None, "
                             "min_length=0, max_length=%d)" % (indent, name, f["max"] or 4000))
            else:
                lines.append("%s%s: %s = Field(min_length=1, max_length=%d)" % (
                    indent, name, t, f["max"] or 4000))
        elif f["type"] == "int":
            if optional:
                lines.append("%s%s: Optional[int] = Field(default=None, "
                             "ge=-1000000000000, le=1000000000000)" % (indent, name))
            else:
                lines.append("%s%s: int = Field(ge=-1000000000000, "
                             "le=1000000000000, strict=True)" % (indent, name))
        elif f["type"] == "float":
            if optional:
                lines.append("%s%s: Optional[float] = Field(default=None, "
                             "ge=-1.0e12, le=1.0e12)" % (indent, name))
            else:
                lines.append("%s%s: float = Field(ge=-1.0e12, le=1.0e12)" % (indent, name))
        elif f["type"] == "bool":
            lines.append("%s%s: %s%s" % (indent, name, "Optional[bool]" if optional else "bool", opt))
        else:
            lines.append("%s%s: %s%s" % (
                indent, name, "Optional[%s]" % t if optional else t, opt))
    return lines


def _storage_body(fields: List[dict]) -> str:
    has_temporal = any(f["type"] in ("datetime", "date") for f in fields)
    lines = ["    data = payload.model_dump()"]
    if has_temporal:
        lines.append("    for key, value in list(data.items()):")
        lines.append("        if isinstance(value, (datetime, date)):")
        lines.append("            data[key] = value.isoformat()")
    lines.append("    return {k: (int(v) if isinstance(v, bool) else v) for k, v in data.items()}")
    return "\n".join(lines)


