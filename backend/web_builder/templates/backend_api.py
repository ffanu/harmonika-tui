def install(app: FastAPI) -> None:
    """Attach security headers, rate limiting and redacted request logging."""

    @app.middleware("http")
    async def harden(request: Request, call_next):
        started = time.monotonic()
        bucket = _BUCKETS[_client(request)]
        now = time.monotonic()
        while bucket and bucket[0] < now - 60:
            bucket.popleft()
        if len(bucket) >= RATE_LIMIT_PER_MIN:
            return JSONResponse({"detail": "rate_limited"}, status_code=429,
                                headers={"X-Content-Type-Options": "nosniff"})
        bucket.append(now)
        response = await call_next(request)
        response.headers["X-Content-Type-Options"] = "nosniff"
        response.headers["X-Frame-Options"] = "DENY"
        response.headers["Referrer-Policy"] = "no-referrer"
        response.headers["Cache-Control"] = "no-store"
        response.headers["X-Request-Id"] = request.headers.get("x-request-id") or uuid.uuid4().hex
        _log.info("%s %s -> %s %.1fms", request.method, _safe_path(request),
                  response.status_code, (time.monotonic() - started) * 1000)
        return response


