PAYMENT_CORE_TEMPLATE = '''"""Payment core (auto-generated, stdlib only): webhook signature verification.

This module verifies provider signatures and records events idempotently.
It NEVER claims money was processed: an intent becomes 'paid' only when
a separate server-side provider reconciliation confirms settled funds.
APP_PAYMENT_TRUST_WEBHOOK alone never authorizes a paid status.
"""
from __future__ import annotations

import hashlib
import hmac
import os
import sqlite3
import time
from contextlib import contextmanager
from typing import Optional

DATABASE = os.environ.get("APP_DATABASE", "data/@@PROJECT@@.sqlite")
CURRENCY = "@@CURRENCY@@"
MIN_MINOR = 100
MAX_MINOR = 200000000000

SCHEMA_SQL = (
    "CREATE TABLE IF NOT EXISTS payment_intents ("
    "id TEXT PRIMARY KEY, amount_minor INTEGER NOT NULL, currency TEXT NOT NULL, "
    "status TEXT NOT NULL DEFAULT 'pending', "
    "created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP); "
    "CREATE TABLE IF NOT EXISTS payment_events ("
    "event_id TEXT PRIMARY KEY, provider TEXT NOT NULL, intent_id TEXT, "
    "received_at REAL NOT NULL, verified INTEGER NOT NULL);"
)


class PaymentConfigError(RuntimeError):
    pass


def require_server_key(env_name: str) -> str:
    key = os.environ.get(env_name, "")
    if len(key) < 16:
        raise PaymentConfigError("payment_key_required: set " + env_name)
    return key


def amount_minor(amount: float, currency: str = CURRENCY) -> int:
    if currency != CURRENCY:
        raise ValueError("currency_not_allowed")
    minor = int(round(float(amount) * 100))
    if not MIN_MINOR <= minor <= MAX_MINOR:
        raise ValueError("amount_out_of_bounds")
    return minor


def verify_midtrans(payload: dict, server_key: str) -> bool:
    """Midtrans Snap: sha512(order_id + status_code + gross_amount + server_key)."""
    raw = "{order_id}{status_code}{gross_amount}{server_key}".format(
        order_id=payload.get("order_id", ""),
        status_code=payload.get("status_code", ""),
        gross_amount=payload.get("gross_amount", ""),
        server_key=server_key).encode()
    expected = hashlib.sha512(raw).hexdigest()
    return hmac.compare_digest(expected, str(payload.get("signature_key", "")))


def verify_stripe(sig_header: str, payload_bytes: bytes, secret: str,
                  now: Optional[float] = None, tolerance_s: int = 300) -> bool:
    """Stripe scheme: t=<ts>,v1=<hex hmac of "<ts>.<payload>">."""
    parts = dict(p.split("=", 1) for p in (sig_header or "").split(",") if "=" in p)
    timestamp, signature = parts.get("t", ""), parts.get("v1", "")
    if not timestamp.isdigit() or not signature:
        return False
    now = time.time() if now is None else now
    if abs(now - int(timestamp)) > tolerance_s:
        return False
    signed = timestamp.encode() + b"." + payload_bytes
    expected = hmac.new(secret.encode(), signed, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, signature)


def verify_xendit(callback_token: str, header_token: str) -> bool:
    if not callback_token:
        raise PaymentConfigError("payment_key_required: set APP_XENDIT_CALLBACK_TOKEN")
    return hmac.compare_digest((header_token or "").encode(), callback_token.encode())


@contextmanager
def connect():
    folder = os.path.dirname(DATABASE)
    if folder:
        os.makedirs(folder, exist_ok=True)
    conn = sqlite3.connect(DATABASE, timeout=5)
    conn.row_factory = sqlite3.Row
    conn.executescript(SCHEMA_SQL)
    try:
        yield conn
    finally:
        conn.close()


def create_intent(intent_id: str, amount: float, currency: str = CURRENCY) -> dict:
    minor = amount_minor(amount, currency)
    with connect() as conn:
        conn.execute(
            "INSERT OR IGNORE INTO payment_intents (id, amount_minor, currency) "
            "VALUES (?, ?, ?)", (intent_id, minor, currency))
        conn.commit()
        row = conn.execute(
            "SELECT id, amount_minor, currency, status FROM payment_intents WHERE id = ?",
            (intent_id,)).fetchone()
    return dict(row)


def record_event(conn: sqlite3.Connection, event_id: str, provider: str,
                 intent_id: str, verified: bool) -> bool:
    """Idempotency gate: the same webhook event id is processed at most once."""
    try:
        conn.execute(
            "INSERT INTO payment_events (event_id, provider, intent_id, received_at, verified) "
            "VALUES (?, ?, ?, ?, ?)",
            (provider + ":" + event_id, provider, intent_id, time.time(), 1 if verified else 0))
        return True
    except sqlite3.IntegrityError:
        return False


def apply_webhook(provider: str, event_id: str, intent_id: str,
                  amount_minor_value: int, verified: bool) -> dict:
    """Record only. Provider API reconciliation is required before marking paid."""
    if not verified:
        return {"recorded": False, "paid": False, "reason": "signature_invalid"}
    with connect() as conn:
        if not record_event(conn, event_id, provider, intent_id, True):
            return {"recorded": False, "paid": False, "reason": "duplicate_event"}
        row = conn.execute(
            "SELECT amount_minor, currency, status FROM payment_intents WHERE id = ?",
            (intent_id,)).fetchone()
        if row is None:
            conn.commit()
            return {"recorded": True, "paid": False, "reason": "unknown_intent"}
        if int(amount_minor_value) != row["amount_minor"]:
            conn.commit()
            return {"recorded": True, "paid": False, "reason": "amount_mismatch"}
        conn.commit()
    return {"recorded": True, "paid": False, "status": "webhook_verified_pending_review"}
'''

